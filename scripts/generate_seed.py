"""
Generates realistic fictional sample data and writes it to sql/02_seed_data.sql.

A fixed random seed means the output is the same every time, so the
analysis results in the README can be reproduced.

Run from the project root:
    python scripts/generate_seed.py
"""

import random
from datetime import date, timedelta

random.seed(42)

CLINICS = [(1, "Galway Central", "Galway"), (2, "Salthill Health", "Salthill"), (3, "Oranmore Medical", "Oranmore")]

DOCTORS = [
    (1, "Dr. Claire Nolan", "General Practice", 1),
    (2, "Dr. Mark Doyle", "Physiotherapy", 1),
    (3, "Dr. Emma Quinn", "General Practice", 2),
    (4, "Dr. Liam Burke", "Dermatology", 3),
    (5, "Dr. Sarah Kenny", "General Practice", 3),
    (6, "Dr. Paul Hayes", "Physiotherapy", 2),
]

SERVICES = [
    (1, "GP Consultation", 15, 60.0),
    (2, "Physio Session", 45, 70.0),
    (3, "Skin Check", 30, 90.0),
    (4, "Blood Test", 10, 35.0),
    (5, "Follow-up", 10, 40.0),
]

# Which services each specialty offers
SPECIALTY_SERVICES = {
    "General Practice": [1, 4, 5],
    "Physiotherapy": [2, 5],
    "Dermatology": [3, 5],
}

FIRST = ["Mary", "John", "Aoife", "Sean", "Niamh", "Patrick", "Ciara", "Declan", "Orla", "Eoin",
         "Sinead", "Conor", "Emma", "Ronan", "Laura", "Kevin", "Grace", "Mark", "Amy", "Cathal"]
LAST = ["O'Brien", "Murphy", "Kelly", "Walsh", "Byrne", "Ryan", "Doyle", "Burke", "Nolan", "Quinn"]
COUNTIES = ["Galway"] * 6 + ["Mayo", "Clare", "Roscommon"]


def sql_text(value):
    return "'" + value.replace("'", "''") + "'"


def main():
    patients = []
    for pid in range(1, 41):
        name = f"{random.choice(FIRST)} {random.choice(LAST)}"
        patients.append((pid, name, random.randint(1945, 2005), random.choice(COUNTIES)))

    appointments = []
    start = date(2026, 1, 5)
    for appt_id in range(1, 241):
        doctor = random.choice(DOCTORS)
        service_id = random.choice(SPECIALTY_SERVICES[doctor[2]])
        appt_date = start + timedelta(days=random.randint(0, 175))
        lead_days = random.choice([0, 1, 2, 3, 5, 7, 10, 14, 21, 28])
        booked_on = appt_date - timedelta(days=lead_days)

        # Bookings made far in advance are more likely to be missed
        no_show_chance = 0.05 + lead_days * 0.008
        roll = random.random()
        status = "no-show" if roll < no_show_chance else "cancelled" if roll < no_show_chance + 0.08 else "attended"

        appointments.append((appt_id, random.choice(patients)[0], doctor[0], service_id,
                             booked_on.isoformat(), appt_date.isoformat(), status))

    lines = ["-- Generated by scripts/generate_seed.py (fictional data)", ""]
    lines.append("INSERT INTO clinic VALUES")
    lines.append(",\n".join(f"  ({c[0]}, {sql_text(c[1])}, {sql_text(c[2])})" for c in CLINICS) + ";\n")
    lines.append("INSERT INTO doctor VALUES")
    lines.append(",\n".join(f"  ({d[0]}, {sql_text(d[1])}, {sql_text(d[2])}, {d[3]})" for d in DOCTORS) + ";\n")
    lines.append("INSERT INTO service VALUES")
    lines.append(",\n".join(f"  ({s[0]}, {sql_text(s[1])}, {s[2]}, {s[3]})" for s in SERVICES) + ";\n")
    lines.append("INSERT INTO patient VALUES")
    lines.append(",\n".join(f"  ({p[0]}, {sql_text(p[1])}, {p[2]}, {sql_text(p[3])})" for p in patients) + ";\n")
    lines.append("INSERT INTO appointment VALUES")
    lines.append(",\n".join(
        f"  ({a[0]}, {a[1]}, {a[2]}, {a[3]}, '{a[4]}', '{a[5]}', '{a[6]}')" for a in appointments) + ";")

    with open("sql/02_seed_data.sql", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(patients)} patients and {len(appointments)} appointments")


if __name__ == "__main__":
    main()
